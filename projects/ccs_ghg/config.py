"""Unified configuration for the CCS GHG project.

Combines infrastructure assumptions (grid, transport, storage) with
per-industry data (emission profiles + capture cases) into a single
config hierarchy.
"""

# pylint: disable=missing-function-docstring, too-many-instance-attributes
from dataclasses import dataclass, field, fields
from typing import Dict, List, Optional

from utils.io import yaml_to_dict


@dataclass
class CCSConstants:
    """Configurable assumptions for CCS grid/infrastructure calculations.

    Physical constants (molecular weights, unit conversions) live in
    projects.ccs_ghg.constants.
    """

    # Grid and methane
    gwp_ch4: float
    methane_leak_rate: float
    grid_tco2_per_mwh: float
    grid_tch4_per_mwh: float
    tch4_per_mmbtu_pipeline_gas: float
    eor_gas_turbine_efficiency: float
    # Oil and storage
    oil_tco2_per_bbl: float
    recovery_factor_bbl_per_tco2: float
    # EPA emission factors (40 CFR 98 Table C-1)
    natural_gas_tco2_per_mmbtu: float
    coal_tco2_per_mmbtu: float
    case_name: str = "us_basic"
    state: Optional[str] = None
    # State-avg heat rate of the natural-gas fleet (MMBtu of gas per MWh of
    # electricity generated by NG plants). Used only by `power_ng_retrofit`
    # industry variant (industries with heat_rate_btu_per_kwh=None fall back
    # to this state value * 1000). Optional so that YAMLs which never touch
    # power_ng_retrofit don't need to supply it.
    grid_ng_heat_rate_mmbtu_per_mwh: Optional[float] = None

    @classmethod
    def from_dict(cls, d: dict) -> "CCSConstants":
        field_names = {f.name for f in fields(cls)}
        mapped = {k: d[k] for k in field_names if k in d}
        return cls(**mapped)


@dataclass
class IndustryInput:
    """Per-industry emission profile (one variant of an industry)."""

    industrial_product: str
    simple_product_name: str
    unit: str
    process_tco2_per_unit_product: float
    process_tch4_throughput_per_unit_product: float
    combustion_tch4_throughput_per_unit_product: float
    ccs_applied_to: str
    combustion_tco2_per_unit_product: Optional[float] = None
    heat_rate_btu_per_kwh: Optional[float] = None
    fuel_type: Optional[str] = None
    electricity_mwh_per_unit_product: float = 0.0
    direct_process_tch4_per_unit_product: float = 0.0
    direct_combustion_tch4_per_unit_product: float = 0.0
    process_capture_fraction: float = 0.0
    combustion_capture_fraction: float = 0.0
    # True if natural gas / methane is a material feedstock OR primary process
    # heat source for the industry — used for filtering/coloring in plots and
    # for "methane-based industries" subtotals in publications.
    is_methane_based: bool = False

    @classmethod
    def from_dict(cls, d: dict) -> "IndustryInput":
        field_names = {f.name for f in fields(cls)}
        return cls(**{k: v for k, v in d.items() if k in field_names})


@dataclass
class IndustryConfig:
    """Combined emission profiles and capture cases for one industry."""

    simple_product_name: str
    emission_profiles: List[IndustryInput]
    capture_cases: list

    @classmethod
    def from_dict(cls, name: str, d: dict) -> "IndustryConfig":
        capture_cases = d.get("capture_cases", []) or []
        primary = [c for c in capture_cases if c.get("primary_case") == 1]
        capture_rate = (
            primary[0].get("co2_stream_capture_rate", 0.0) if primary else 0.0
        )

        profiles = []
        for p in d.get("emission_profiles", []) or []:
            p_with_name = {**p, "simple_product_name": name}
            profile = IndustryInput.from_dict(p_with_name)
            if profile.ccs_applied_to == "process":
                profile.process_capture_fraction = capture_rate
            elif profile.ccs_applied_to == "combustion":
                profile.combustion_capture_fraction = capture_rate
            profiles.append(profile)

        return cls(
            simple_product_name=name,
            emission_profiles=profiles,
            capture_cases=capture_cases,
        )


@dataclass
class CCSProjectConfig:
    """Top-level combined configuration for the CCS GHG project."""

    constants: CCSConstants
    industries: Dict[str, IndustryConfig]
    transport: list
    storage: list
    state_constants: Dict[str, CCSConstants] = field(default_factory=dict)

    @classmethod
    def from_yaml(
        cls,
        infrastructure_path: str,
        industries_path: str,
    ) -> "CCSProjectConfig":
        infra = yaml_to_dict(infrastructure_path)
        ind_raw = yaml_to_dict(industries_path)

        base = {**infra["constants"], **infra.get("emission_factors", {})}
        constants = CCSConstants.from_dict(base)

        state_blocks = infra.get("states") or {}
        if not state_blocks:
            raise ValueError(
                f"{infrastructure_path} defines no `states:` block. "
                "Every run must specify per-state overrides for at least one state."
            )
        state_constants: Dict[str, CCSConstants] = {}
        for state_code, overrides in state_blocks.items():
            merged = {**base, **(overrides or {})}
            sc = CCSConstants.from_dict(merged)
            sc.state = state_code
            sc.case_name = f"{base.get('case_name', 'case')}_{state_code}"
            state_constants[state_code] = sc

        industries = {}
        for name, data in (ind_raw.get("industries", {}) or {}).items():
            industries[name] = IndustryConfig.from_dict(name, data)

        return cls(
            constants=constants,
            industries=industries,
            transport=infra["transport"],
            storage=infra["storage"],
            state_constants=state_constants,
        )

    def constants_for_state(self, state: str) -> CCSConstants:
        """Return per-state constants; raise loudly if state is not defined."""
        try:
            return self.state_constants[state]
        except KeyError as exc:
            available = ", ".join(sorted(self.state_constants)) or "<none>"
            raise KeyError(
                f"No infrastructure constants defined for project_state={state!r}. "
                f"Add a `states.{state}:` block to the infrastructure YAML. "
                f"Currently defined: {available}."
            ) from exc

    def get_all_industry_inputs(self) -> List[IndustryInput]:
        """Flatten all emission profiles across all industries."""
        result = []
        for ic in self.industries.values():
            result.extend(ic.emission_profiles)
        return result

    def get_all_capture_cases(self) -> list:
        """Flatten all capture cases, injecting 'industry' key for each."""
        result = []
        for name, ic in self.industries.items():
            for case in ic.capture_cases:
                result.append({**case, "industry": name})
        return result
